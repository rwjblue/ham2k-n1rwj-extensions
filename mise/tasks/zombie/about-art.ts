#!/usr/bin/env -S node --experimental-strip-types
//[MISE] description="Regenerate the offline Zombie About image (requires chrome-headless-shell and ImageMagick 7; set ZOMBIE_ART_CHROME for an explicit executable)"
//[MISE] depends=["local-tasks-npm-install"]

import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import { pathToFileURL } from 'node:url'
import { zombiePanelPreview } from '../../../extensions/contests/n1rwj-zombie/src/panel-preview.ts'

// Chrome renders the SVG faithfully, including inherited fills and gradients
// that ImageMagick's built-in SVG reader drops. A fresh profile and font-free,
// self-contained SVG keep this separate from the user's browser session.
// Verified with Chrome for Testing 153.0.8010.12 and ImageMagick 7.1.2-30.
await mkdir('dist', { recursive: true })
const temporary = await mkdtemp(resolve('dist/.zombie-about-art-'))
const chrome = process.env.ZOMBIE_ART_CHROME ?? 'chrome-headless-shell'
let raster: Buffer
try {
  const source = join(temporary, 'art.svg')
  const screenshot = join(temporary, 'art.png')
  await writeFile(
    source,
    zombiePanelPreview.replace('width="640" height="640"', 'width="320" height="320"'),
  )
  const rendered = spawnSync(
    chrome,
    [
      '--headless',
      '--disable-gpu',
      '--disable-background-networking',
      '--no-first-run',
      '--no-default-browser-check',
      '--disable-extensions',
      '--hide-scrollbars',
      '--force-device-scale-factor=1',
      '--default-background-color=00000000',
      '--window-size=320,320',
      `--user-data-dir=${join(temporary, 'profile')}`,
      `--screenshot=${screenshot}`,
      pathToFileURL(source).href,
    ],
    { timeout: 30_000, maxBuffer: 1_000_000 },
  )
  if (rendered.error) throw rendered.error
  if (rendered.status !== 0) throw new Error(rendered.stderr.toString())
  raster = await readFile(screenshot)
} finally {
  await rm(temporary, { recursive: true, force: true })
}

// Palette conversion and metadata removal apply only to the already rendered
// PNG, never SVG. No network request or image decoder runs in the extension.
const result = spawnSync(
  'magick',
  [
    'png:-',
    '-depth',
    '8',
    '+dither',
    '-colors',
    '256',
    '-strip',
    '-define',
    'png:compression-level=9',
    '-define',
    'png:exclude-chunks=date,time',
    'PNG8:-',
  ],
  { input: raster, maxBuffer: 1_000_000 },
)
if (result.error) throw result.error
if (result.status !== 0) throw new Error(result.stderr.toString())
const png = result.stdout
await writeFile('dist/zombie-shuffle.png', png)
const sourceHash = createHash('sha256').update(zombiePanelPreview).digest('hex')
const output = 'extensions/contests/n1rwj-zombie/src/about-art.ts'
await writeFile(
  output,
  `// Copyright (c) 2026 Robert Jackson (N1RWJ)
// SPDX-License-Identifier: MPL-2.0
// Generated by mise run zombie:about-art from panel-preview.ts; do not edit.
// Original Zombie Shuffle picker artwork; 320 × 320 PNG, ${png.length} bytes.
export const zombieAboutArtworkSourceHash =
  '${sourceHash}'
export const zombieAboutArtwork =
  'data:image/png;base64,${png.toString('base64')}'
`,
)
console.log(`Generated ${output}: ${png.length} PNG bytes; source SHA-256 ${sourceHash}`)
